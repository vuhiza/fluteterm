//! Persistent sessions.
//!
//! * **tmux backend** (default when tmux is installed): every tab is a session
//!   on a private tmux server (`tmux -L fluteterm`) with tmux's own UI turned
//!   off. Quitting fluteterm only detaches, so shells, Claude sessions, builds
//!   and scrollback keep running; the next start re-attaches to all of them.
//! * **plain backend**: tabs are restored from `session.json` (directory,
//!   kind, title, Claude conversation via `--resume`) and the last
//!   `scrollback_lines` of each tab are replayed dimmed.
//!
//! The layout itself always lives in `~/.config/fluteterm/session.json`.

use std::path::PathBuf;
use std::process::{Command, Stdio};

use serde::{Deserialize, Serialize};
use serde_json::Value;

use crate::ext::TabKind;
use crate::util;

pub const TMUX_SOCKET: &str = "fluteterm";
/// Sessions created before the rename (named `drp-N`) live on the old server;
/// they are re-attached there so running tabs survive the upgrade.
pub const LEGACY_TMUX_SOCKET: &str = "drpdown";
const LEGACY_PREFIX: &str = "drp-";

/// Which tmux server a session lives on.
pub fn socket_for(name: &str) -> &'static str {
    if name.starts_with(LEGACY_PREFIX) { LEGACY_TMUX_SOCKET } else { TMUX_SOCKET }
}

#[derive(Serialize, Deserialize, Default, Debug, Clone)]
pub struct SavedSession {
    pub version: u32,
    pub next_id: u64,
    pub active: usize,
    pub tabs: Vec<SavedTab>,
}

#[derive(Serialize, Deserialize, Default, Debug, Clone)]
pub struct SavedTab {
    pub id: u64,
    pub kind: String,
    pub title: Option<String>,
    pub cwd: Option<PathBuf>,
    /// Command the tab was started with (custom profiles).
    pub command: Option<Vec<String>>,
    pub tmux: Option<String>,
    /// Per-extension state (e.g. the Claude session id).
    #[serde(default)]
    pub ext: serde_json::Map<String, Value>,
}

pub fn kind_to_str(k: TabKind) -> String {
    match k {
        TabKind::Shell => "shell".into(),
        TabKind::Claude => "claude".into(),
        TabKind::Orca => "orca".into(),
        TabKind::Custom(c) => format!("custom:{c}"),
    }
}

pub fn kind_from_str(s: &str) -> TabKind {
    match s {
        "claude" => TabKind::Claude,
        "orca" => TabKind::Orca,
        s if s.starts_with("custom:") => TabKind::Custom(s[7..].chars().next().unwrap_or('▸')),
        _ => TabKind::Shell,
    }
}

fn path() -> PathBuf {
    util::config_dir().join("session.json")
}

pub fn scrollback_dir() -> PathBuf {
    util::config_dir().join("scrollback")
}

pub fn load() -> Option<SavedSession> {
    let s = std::fs::read_to_string(path()).ok()?;
    serde_json::from_str(&s).ok()
}

pub fn save(s: &SavedSession) {
    let Ok(json) = serde_json::to_string_pretty(s) else { return };
    let tmp = path().with_extension("json.tmp");
    if std::fs::write(&tmp, json).is_ok() {
        let _ = std::fs::rename(&tmp, path());
    }
}

// ───────────────────────────── tmux ─────────────────────────────

pub fn tmux_path() -> Option<String> {
    util::which("tmux").map(|p| p.display().to_string())
}

pub fn conf_path() -> PathBuf {
    util::config_dir().join("tmux.conf")
}

/// tmux as an invisible session keeper: no status bar, no prefix key, mouse
/// wheel scrolls tmux history, selections are copied through OSC 52.
pub fn write_conf() {
    let shell = util::user_shell();
    let conf = format!(
        r##"# Generated by fluteterm — tmux is only used to keep tab sessions alive.
# Edit ~/.config/fluteterm/tmux.local.conf for your own additions.
set -g status off
set -g prefix None
unbind-key -a -T prefix
set -g escape-time 0
set -g history-limit 50000
set -g default-terminal "tmux-256color"
set -as terminal-features ",xterm-256color:RGB:clipboard:focus:extkeys:hyperlinks:usstyle:strikethrough"
set -g focus-events on
set -g mouse on
set -g set-clipboard on
set -g allow-passthrough on
set -g extended-keys on
set -g set-titles on
set -g set-titles-string "#{{pane_title}}"
set -g destroy-unattached off
set -g exit-empty on
set -g default-shell "{shell}"
set -g default-command ""
setw -g aggressive-resize on
# Scroll position looks like fluteterm's own scrollback badge instead of "[0/0]".
set -g copy-mode-position-format "#[align=right] ↑ #{{copy_position}} "
# Mouse drag copies straight to the macOS clipboard and leaves copy mode.
bind -T copy-mode MouseDragEnd1Pane send -X copy-pipe-and-cancel "pbcopy"
bind -T copy-mode-vi MouseDragEnd1Pane send -X copy-pipe-and-cancel "pbcopy"
if-shell "test -f ~/.config/fluteterm/tmux.local.conf" "source-file ~/.config/fluteterm/tmux.local.conf"
"##
    );
    let _ = std::fs::create_dir_all(util::config_dir());
    let _ = std::fs::write(conf_path(), conf);
}

fn tmux(socket: &str, args: &[&str]) -> Option<String> {
    let t = tmux_path()?;
    let out = Command::new(t)
        .arg("-L")
        .arg(socket)
        .args(args)
        .env("PATH", util::augmented_path())
        .stdin(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .ok()?;
    out.status.success().then(|| String::from_utf8_lossy(&out.stdout).to_string())
}

/// Live fluteterm tmux sessions (current server + pre-rename server).
pub fn tmux_sessions() -> Vec<String> {
    let list = |socket: &str, prefix: &str| -> Vec<String> {
        tmux(socket, &["list-sessions", "-F", "#{session_name}"])
            .map(|s| s.lines().map(String::from).filter(|l| l.starts_with(prefix)).collect())
            .unwrap_or_default()
    };
    let mut v = list(TMUX_SOCKET, "ft-");
    v.extend(list(LEGACY_TMUX_SOCKET, LEGACY_PREFIX));
    v
}

/// Tab id encoded in a session name (`ft-12`, legacy `drp-12`).
pub fn id_from_name(name: &str) -> Option<u64> {
    name.trim_start_matches("ft-").trim_start_matches(LEGACY_PREFIX).parse().ok()
}

pub fn tmux_kill(name: &str) {
    let _ = tmux(socket_for(name), &["kill-session", "-t", &format!("={name}")]);
}

/// PID of the shell (or command) inside the session's pane.
pub fn tmux_pane_pid(name: &str) -> Option<i32> {
    tmux(socket_for(name), &["display-message", "-p", "-t", &format!("{name}:"), "#{pane_pid}"])?.trim().parse().ok()
}

/// Does the program inside the tmux pane have mouse reporting on (vim, htop…)?
pub fn tmux_pane_wants_mouse(name: &str) -> bool {
    tmux(socket_for(name), &["display-message", "-p", "-t", &format!("{name}:"), "#{mouse_any_flag}"]).map(|s| s.trim() == "1").unwrap_or(false)
}

/// Foreground process group of the terminal a process is attached to.
pub fn tty_foreground_of(pid: i32) -> Option<i32> {
    unsafe {
        let mut info: libc::proc_bsdinfo = std::mem::zeroed();
        let size = std::mem::size_of::<libc::proc_bsdinfo>() as i32;
        let n = libc::proc_pidinfo(pid, libc::PROC_PIDTBSDINFO, 0, &mut info as *mut _ as *mut libc::c_void, size);
        (n == size && info.e_tpgid > 0).then_some(info.e_tpgid as i32)
    }
}

/// Program + args that attach to (or create) the tab's tmux session.
pub fn tmux_command(name: &str, id: u64, cwd: &std::path::Path, inner: Option<String>) -> Option<(String, Vec<String>)> {
    let t = tmux_path()?;
    let mut args: Vec<String> = vec![
        "-L".into(),
        socket_for(name).into(),
        "-f".into(),
        conf_path().display().to_string(),
        "new-session".into(),
        "-A".into(),
        "-s".into(),
        name.into(),
        "-c".into(),
        cwd.display().to_string(),
    ];
    let mut env = vec![
        format!("FLUTETERM_TAB_ID={id}"),
        format!("FLUTETERM_SOCKET={}", util::socket_path().display()),
        "COLORTERM=truecolor".into(),
        format!("PATH={}", util::augmented_path()),
    ];
    if let Ok(exe) = std::env::current_exe() {
        env.push(format!("FLUTETERM_BIN={}", exe.display()));
    }
    for e in env {
        args.push("-e".into());
        args.push(e);
    }
    if let Some(cmd) = inner {
        args.push(cmd);
    }
    Some((t, args))
}
